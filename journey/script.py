def L(say, text=None, kind="none", ic="", sub=None):
    return dict(say=say, text=text, kind=kind, ic=ic, sub=sub)


def std(unit, chip, title, say_title, lines, pose, ic, extra=None, hold=0.8):
    return dict(type="std", unit=unit, chip=chip, title=title, pose=pose, ic=ic, extra=extra, hold=hold,
                lines=[L(say_title, sub=title)] + lines)


def chapter(unit, say, tagline):
    return dict(type="chapter", unit=unit, name=UNITS[unit][0], tagline=tagline, pose="g" if unit % 2 else "gm", hold=0.5,
                lines=[L(say, sub=f"第 {unit} 單元：{UNITS[unit][0]}。{tagline}")])


